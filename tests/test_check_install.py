"""Tests of scripts/check_install.py: the installed files and provenance pages.

An install space keeps what an earlier build installed. So the check has to notice a page
that was edited or removed in the checkout after it was installed, and a link of an installed
page whose target isn't installed. A file that has the expected name but can't be read is a
problem too, and a page that can't be read must not stop the check. Each test builds a small
checkout and a small install space in a temporary folder. Run from the repository's root, with
the packages of generators/requirements.txt:

  python3 -m unittest discover -s tests
"""
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from typing import List
import unittest

from scripts import check_install

PAGE = 'provenance/part.md'
PAGE_TEXT = ('# Part\n\n![The part](../docs/images/frames/part.png)\n\n'
             'Generated by [`generators/part.py`](../generators/part.py), after the '
             '[datasheet](https://example.org/datasheet.pdf). See [Frame](#frame).\n')
LINKED_FILES = ('docs/images/frames/part.png', 'generators/part.py')
SHARED_MODULE = 'generators/mesh_export.py'
MESH, MESH_TEXT = 'meshes/part/part.stl', 'mesh'
OWN_FILES = {'LICENSE': 'license', 'package.xml': '<package/>'}
MANIFEST = f"""parts:
  part:
    provenance: {PAGE}
    generator: generators/part.py
    meshes:
      part:
        files:
          part/part.stl:
            sha256: {hashlib.sha256(MESH_TEXT.encode()).hexdigest()}
            license_file: part/part.stl.license
"""
PASSED, FAILED = 0, 1


def write(folder: str, path: str, text: str) -> None:
    """Write a text file at folder/path, with its parent folders."""
    full = os.path.join(folder, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8') as stream:
        stream.write(text)


class InstalledPagesTest(unittest.TestCase):
    """The checks of an install space's provenance pages against a checkout."""

    def setUp(self) -> None:
        """Make a checkout and an install space that hold the same page and what it links."""
        self.folder = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.folder)
        self.checkout = os.path.join(self.folder, 'checkout')
        self.share = os.path.join(self.folder, 'share')
        for root in (self.checkout, self.share):
            write(root, PAGE, PAGE_TEXT)
            for path in LINKED_FILES:
                write(root, path, 'content')

    def page_problems(self) -> List[str]:
        """Return the problems of the installed page against the checkout's page."""
        installed = check_install.read_installed_pages(self.share, {PAGE})
        return check_install.check_pages_are_the_checkouts(installed, {PAGE}, self.checkout)

    def link_problems(self) -> List[str]:
        """Return the problems of the installed page's links."""
        installed = check_install.read_installed_pages(self.share, {PAGE})
        return check_install.check_links_lead_to_installed_files(self.share, installed)

    def test_same_page_and_installed_link_targets_have_no_problems(self) -> None:
        """Check the install space as installed: no problem."""
        self.assertEqual(self.page_problems(), [])
        self.assertEqual(self.link_problems(), [])

    def test_page_edited_in_the_checkout_is_reported(self) -> None:
        """Add a sentence to the checkout's page: the installed page differs."""
        write(self.checkout, PAGE, PAGE_TEXT + 'A new sentence.\n')

        self.assertEqual(self.page_problems(), [f"{PAGE}: differs from the checkout's page"])

    def test_page_removed_from_the_checkout_is_reported(self) -> None:
        """Remove the checkout's page: the install space still holds it, which is reported."""
        os.remove(os.path.join(self.checkout, PAGE))

        self.assertEqual(self.page_problems(),
                         [f"{PAGE}: the checkout doesn't have this page of the manifest"])

    def test_page_that_is_not_installed_is_left_to_the_file_set_check(self) -> None:
        """Remove the installed page: the comparison has nothing to report."""
        os.remove(os.path.join(self.share, PAGE))

        self.assertEqual(self.page_problems(), [])

    def test_installed_page_that_cannot_be_read_is_reported(self) -> None:
        """Put a folder where the installed page should be: it can't be read."""
        os.remove(os.path.join(self.share, PAGE))
        os.mkdir(os.path.join(self.share, PAGE))

        self.assertEqual(self.page_problems(), [f"{PAGE}: the installed page can't be read"])

    def test_links_of_a_page_that_cannot_be_read_are_not_checked(self) -> None:
        """Put a folder where the installed page should be: the link check has nothing to do."""
        os.remove(os.path.join(self.share, PAGE))
        os.mkdir(os.path.join(self.share, PAGE))

        self.assertEqual(self.link_problems(), [])

    def test_link_without_its_installed_target_is_reported(self) -> None:
        """Remove the installed frame picture: the page's link to it is reported."""
        os.remove(os.path.join(self.share, LINKED_FILES[0]))

        self.assertEqual(self.link_problems(),
                         [f"{PAGE}: the link's target ../{LINKED_FILES[0]} isn't installed"])


class GeneratorFilesTest(unittest.TestCase):
    """Every Python file of the checkout's generators/ is expected in an install space."""

    def test_generator_files_are_the_python_files_of_the_folder(self) -> None:
        """List a generators/ folder with a module, a part and another file."""
        checkout = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, checkout)
        for name in ('mesh_export.py', 'part.py', 'requirements.txt'):
            write(checkout, f'generators/{name}', '')

        self.assertEqual(check_install.generator_files(checkout),
                         {'generators/mesh_export.py', 'generators/part.py'})

    def test_generator_files_include_sub_folders_without_pycache(self) -> None:
        """List a helper in a sub-folder and a file in __pycache__: the helper only."""
        checkout = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, checkout)
        for path in ('generators/part.py', 'generators/helpers/colours.py',
                     'generators/__pycache__/part.py', 'generators/helpers/__pycache__/x.py'):
            write(checkout, path, '')

        self.assertEqual(check_install.generator_files(checkout),
                         {'generators/part.py', 'generators/helpers/colours.py'})

    def test_missing_shared_module_is_reported(self) -> None:
        """Leave a shared module out of the installed files: it is missing."""
        expected = {'generators/mesh_export.py', 'generators/part.py'}

        self.assertEqual(check_install.check_file_set({'generators/part.py'}, expected, set()),
                         ['missing: generators/mesh_export.py'])


class FilesCanBeReadTest(unittest.TestCase):
    """An installed file counts only if it can be read, also through a symbolic link."""

    def setUp(self) -> None:
        """Make an install space with the shared module as a file."""
        self.share = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.share)
        write(self.share, SHARED_MODULE, 'content')

    def problems(self) -> List[str]:
        """Return the problems of the shared module's installed path."""
        return check_install.check_files_can_be_read(self.share, [SHARED_MODULE])

    def replace_with_link(self, target: str) -> None:
        """Replace the installed shared module with a symbolic link to the target."""
        os.remove(os.path.join(self.share, SHARED_MODULE))
        os.symlink(target, os.path.join(self.share, SHARED_MODULE))

    def test_file_has_no_problem(self) -> None:
        """Check the module as a plain file: no problem."""
        self.assertEqual(self.problems(), [])

    def test_link_to_a_file_has_no_problem(self) -> None:
        """Replace the module with a link to a file elsewhere, as symbolic installs do."""
        write(self.share, 'elsewhere/mesh_export.py', 'content')
        self.replace_with_link(os.path.join(self.share, 'elsewhere', 'mesh_export.py'))

        self.assertEqual(self.problems(), [])

    def test_link_without_its_target_is_reported(self) -> None:
        """Replace the module with a link to a file that doesn't exist: reported."""
        self.replace_with_link(os.path.join(self.share, 'nowhere.py'))

        self.assertEqual(self.problems(), [f"{SHARED_MODULE}: isn't a file that can be read"])


class CheckInstallCommandTest(unittest.TestCase):
    """The command itself, run on a small checkout and its install space.

    The checkout holds a copy of scripts/check_install.py, which compares the install space
    with the checkout that it lies in, one part's page and generator, and a shared module. The
    install space holds what the package installs for that checkout.
    """

    def setUp(self) -> None:
        """Make the checkout and a complete install space."""
        self.folder = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.folder)
        self.checkout = os.path.join(self.folder, 'checkout')
        self.prefix = os.path.join(self.folder, 'install')
        self.share = os.path.join(self.prefix, 'share', check_install.PACKAGE)
        os.makedirs(os.path.join(self.checkout, 'scripts'))
        shutil.copy(check_install.__file__, os.path.join(self.checkout, 'scripts'))
        for root in (self.checkout, self.share):
            write(root, PAGE, PAGE_TEXT)
            for path in LINKED_FILES + (SHARED_MODULE,):
                write(root, path, 'content')
        write(self.share, 'meshes/manifest.yaml', MANIFEST)
        write(self.share, MESH, MESH_TEXT)
        write(self.share, MESH + '.license', 'license')
        for path, text in OWN_FILES.items():
            write(self.share, path, text)

    def run_command(self) -> 'subprocess.CompletedProcess[str]':
        """Run the checkout's check_install.py on the install prefix, for ROS 2."""
        return subprocess.run([sys.executable, os.path.join(self.checkout, 'scripts',
                                                            'check_install.py'),
                               self.prefix, '2'], check=False, capture_output=True, text=True)

    def assert_reported(self, result: 'subprocess.CompletedProcess[str]',
                        problems: List[str]) -> None:
        """Fail unless the command failed, printed the problems and ended with its summary."""
        self.assertEqual(result.returncode, FAILED, result.stderr)
        self.assertEqual(result.stderr, '')
        lines = result.stdout.splitlines()
        self.assertEqual(lines[:-1], problems)
        self.assertTrue(lines[-1].endswith(f'{len(problems)} problems'), lines[-1])

    def test_complete_install_passes(self) -> None:
        """Run the command on the install space as made: no problem."""
        result = self.run_command()

        self.assertEqual(result.returncode, PASSED, result.stdout + result.stderr)
        self.assertTrue(result.stdout.endswith('0 problems\n'), result.stdout)

    def test_page_that_is_a_folder_is_reported_with_the_other_problems(self) -> None:
        """Put a folder where the installed page should be, and remove the frame picture.

        The command reports the page as missing and as unreadable, the picture as missing,
        and ends with its summary.
        """
        os.remove(os.path.join(self.share, PAGE))
        os.mkdir(os.path.join(self.share, PAGE))
        os.remove(os.path.join(self.share, LINKED_FILES[0]))

        self.assert_reported(self.run_command(),
                             [f'missing: {LINKED_FILES[0]}', f'missing: {PAGE}',
                              f"{PAGE}: the installed page can't be read"])

    @unittest.skipIf(os.geteuid() == 0, 'root reads a file without read permission')
    def test_page_without_read_permission_is_reported(self) -> None:
        """Take the read permission from the installed page: reported, with the summary."""
        os.chmod(os.path.join(self.share, PAGE), 0)

        self.assert_reported(self.run_command(),
                             [f"{PAGE}: isn't a file that can be read",
                              f"{PAGE}: the installed page can't be read"])

    def test_shared_module_as_a_link_without_its_target_is_reported(self) -> None:
        """Replace the installed shared module with a link to a file that doesn't exist."""
        os.remove(os.path.join(self.share, SHARED_MODULE))
        os.symlink(os.path.join(self.folder, 'nowhere.py'),
                   os.path.join(self.share, SHARED_MODULE))

        self.assert_reported(self.run_command(),
                             [f"{SHARED_MODULE}: isn't a file that can be read"])

    def test_shared_module_as_a_link_to_the_checkouts_file_passes(self) -> None:
        """Replace the installed shared module with a link to the checkout's module."""
        os.remove(os.path.join(self.share, SHARED_MODULE))
        os.symlink(os.path.join(self.checkout, SHARED_MODULE),
                   os.path.join(self.share, SHARED_MODULE))

        result = self.run_command()

        self.assertEqual(result.returncode, PASSED, result.stdout + result.stderr)


if __name__ == '__main__':
    unittest.main()
